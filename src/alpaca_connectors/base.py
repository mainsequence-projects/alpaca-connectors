"""The declarative base of every table this application owns (ms-markets 5.0.0, issue 95).

Hand-written tables, the bars storages and the contract instances the ms-markets factories build
are all declared on ``ProjectBase``, and the migration provider targets its metadata: it holds
this application's tables and no Markets table. A key to a Markets table passes Markets' own
column object (``ForeignKey(AssetTable.__table__.c.uid)``), so no Markets table is copied here
and an autogenerated revision never compares, or drops, anything Markets owns.
"""

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

from metatables import sqlalchemy_naming_convention


class ProjectBase(DeclarativeBase):
    """This application's tables, named with MetaTables' constraint naming convention."""

    metadata = MetaData(naming_convention=sqlalchemy_naming_convention())
